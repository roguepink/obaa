/* ステージ番号(0〜99)から、そのステージの中身を作る(毎回同じ結果になる) */
function makeStage(i) {
  var round = Math.floor(i / 25);                  // 何回目の登場か(0〜3)
  var ti = i % 25, ai = (i + round * 7) % 25;
  var th = i === 99 ? FINAL_THEME : THEMES[ti], ar = AREAS[i === 99 ? 9 : ai];
  var rank = i === 99 ? 3 : round;
  var gims = [];
  if (i > 0) {
    gims.push(GIM_ORDER[(i * 7 + 3) % GIM_ORDER.length]);
    if (i >= 20) { var g2 = GIM_ORDER[(i * 3 + 5) % GIM_ORDER.length]; if (gims.indexOf(g2) < 0) gims.push(g2); }
  }
  if (i === 1) gims = [];
  if (th.drop && gims.indexOf('litter') < 0) gims.push('litter');
  if (ar.ice && gims.indexOf('ice') < 0) gims.push('ice');
  if (i < 10) gims = gims.filter(function (g) { return g !== 'dark' && g !== 'wind' && g !== 'ice'; }).slice(0, i < 5 ? 1 : 2);
  var pats = ['throw', 'spread'];
  if (i >= 3 || rank >= 1) pats.push(['row', 'roll', 'rain', 'summon'][ti % 4]);
  if (rank >= 1) pats.push(['roll', 'rain', 'summon', 'row'][ti % 4]);
  if (rank >= 2) { pats.push('row'); pats.push('rain'); }
  if (rank >= 3) { pats.push('roll'); pats.push('summon'); }
  var bd = {}; for (var k in th.boss) bd[k] = th.boss[k];
  if (rank === 1) { bd.c = '#7f8c9a'; bd.mech = true; }
  var foes = th.foes;
  if (i === 99) { foes = []; THEMES.forEach(function (t) { foes.push(t.foes[0]); }); }
  return {
    i: i, no: i + 1, area: ar, theme: th, rank: rank, foes: foes,
    title: i === 99 ? '最終決戦 ' + th.n : ar.n + ' 〜' + th.n + '〜',
    boss: { d: bd, name: (i === 99 ? '' : RANK_NAME[rank]) + th.bn, pats: pats, move: BOSS_MOVES[(i + round) % 4],
      scale: rank === 2 ? 1.35 : rank === 3 ? 1.2 : 1, crown: rank === 3, final: i === 99 },
    weapon: i % 10, gims: gims, key: ai
  };
}
